import crypto from 'crypto'

function getQrSecret(): string {
  return (
    process.env.QR_SIGNING_SECRET?.trim() ||
    process.env.SUPABASE_SERVICE_ROLE_KEY?.trim() ||
    'mite-canteen-qr-fallback-secret'
  )
}

/**
 * Generates an HMAC-SHA256 signed QR token bound to an entity ID and reference code.
 * Format: <entityId>.<ref>.<hmac_base64url>
 */
export function generateSignedQrToken(entityId: string, refCode: string): string {
  const payload = `${entityId}.${refCode}`
  const sig = crypto
    .createHmac('sha256', getQrSecret())
    .update(payload)
    .digest('base64url')
  return `${payload}.${sig}`
}

/**
 * Verifies an HMAC-SHA256 signed QR token generated by generateSignedQrToken
 * (or legacy 2-part payload.sig formats).
 */
export function verifySignedQrToken(token: string): {
  isSignedFormat: boolean
  valid: boolean
  entityId?: string
  refCode?: string
} {
  const parts = token.split('.')
  if (parts.length !== 3) {
    return { isSignedFormat: false, valid: false }
  }
  const [entityId, refCode, sig] = parts
  if (!entityId || !refCode || !sig) {
    return { isSignedFormat: true, valid: false }
  }
  const expected = crypto
    .createHmac('sha256', getQrSecret())
    .update(`${entityId}.${refCode}`)
    .digest('base64url')

  const sigBuf = Buffer.from(sig)
  const expBuf = Buffer.from(expected)
  if (sigBuf.length !== expBuf.length) {
    return { isSignedFormat: true, valid: false }
  }
  const valid = crypto.timingSafeEqual(sigBuf, expBuf)
  return { isSignedFormat: true, valid, entityId, refCode }
}

/**
 * Parses a raw QR string (plain token, JSON payload, or URL) into a candidate token/code.
 */
export function parseScannedQrPayload(raw: string): {
  qrToken: string | null
  code: string | null
} {
  const trimmed = raw.trim()
  if (!trimmed) return { qrToken: null, code: null }

  if (trimmed.startsWith('{') && trimmed.endsWith('}')) {
    try {
      const parsed = JSON.parse(trimmed) as Record<string, unknown>
      const token =
        typeof parsed.qr_token === 'string'
          ? parsed.qr_token
          : typeof parsed.token === 'string'
            ? parsed.token
            : null
      const code = typeof parsed.code === 'string' ? parsed.code.trim().toUpperCase() : null
      return { qrToken: token?.trim() || null, code }
    } catch {
      // Fall through to raw token handling
    }
  }

  if (trimmed.startsWith('http://') || trimmed.startsWith('https://')) {
    try {
      const url = new URL(trimmed)
      const tokenParam = url.searchParams.get('token') || url.searchParams.get('qr')
      const pathMatch = url.pathname.match(/\/orders\/([A-Za-z]-\d{4})/i)
      return {
        qrToken: tokenParam?.trim() || null,
        code: pathMatch ? pathMatch[1].toUpperCase() : null,
      }
    } catch {
      // Fall through
    }
  }

  if (/^[A-Za-z]-\d{4}$/.test(trimmed)) {
    return { qrToken: null, code: trimmed.toUpperCase() }
  }

  return { qrToken: trimmed, code: null }
}
